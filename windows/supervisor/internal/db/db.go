// Package db provisions and runs the optional bundled MariaDB or PostgreSQL
// server. External databases and SQLite need nothing from here.
package db

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"syscall"
	"time"

	"github.com/mstan/nextcloud-server/windows/supervisor/internal/config"
	"github.com/mstan/nextcloud-server/windows/supervisor/internal/proc"
)

// Bundled reports whether ncwin should run a database server itself.
func Bundled(c config.Config) bool {
	return c.Database.Type != "sqlite" && c.Database.Mode == "bundled"
}

func binDir(c config.Config) string {
	sub := map[string]string{"mysql": "mariadb", "pgsql": "pgsql"}[c.Database.Type]
	return filepath.Join(c.Paths.InstallDir, sub, "bin")
}

func dataDir(c config.Config) string {
	return filepath.Join(filepath.FromSlash(c.DBDir()), c.Database.Type)
}

// superSecretPath holds the bundled server's superuser password.
func superSecretPath(c config.Config) string {
	return filepath.Join(filepath.FromSlash(c.DBDir()), c.Database.Type+"-superuser.secret")
}

func readSecret(c config.Config) (string, error) {
	b, err := os.ReadFile(superSecretPath(c))
	return strings.TrimSpace(string(b)), err
}

func randomSecret() string {
	b := make([]byte, 24)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}

func myIni(c config.Config) string {
	return filepath.Join(filepath.FromSlash(c.GeneratedDir()), "my.ini")
}

func writeMyIni(c config.Config) error {
	ini := fmt.Sprintf(`# Generated by ncwin. Do not edit.
[mysqld]
datadir=%s
port=%d
bind-address=127.0.0.1
skip-name-resolve
character-set-server=utf8mb4
collation-server=utf8mb4_general_ci
transaction_isolation=READ-COMMITTED
binlog_format=ROW
innodb_file_per_table=1
innodb_buffer_pool_size=512M
max_allowed_packet=256M
log-error=%s
`, filepath.ToSlash(dataDir(c)), c.Database.Port, c.LogDir()+"/mariadb.err")
	if err := os.MkdirAll(filepath.Dir(myIni(c)), 0o755); err != nil {
		return err
	}
	return os.WriteFile(myIni(c), []byte(ini), 0o600)
}

// Initialized reports whether the bundled server's data directory exists.
func Initialized(c config.Config) bool {
	_, err := os.Stat(dataDir(c))
	return err == nil
}

// Init creates the data directory, superuser, Nextcloud database and user.
// It is run once by `ncwin setup`; the server is started and stopped around it.
func Init(ctx context.Context, c config.Config, logf *os.File) error {
	if Initialized(c) {
		return fmt.Errorf("%s already exists", dataDir(c))
	}
	if err := os.MkdirAll(filepath.FromSlash(c.DBDir()), 0o700); err != nil {
		return err
	}
	super := randomSecret()
	if err := os.WriteFile(superSecretPath(c), []byte(super), 0o600); err != nil {
		return err
	}
	run := func(name string, args ...string) error {
		cmd := exec.CommandContext(ctx, filepath.Join(binDir(c), name), args...)
		cmd.Stdout, cmd.Stderr = logf, logf
		cmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true}
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		return nil
	}
	switch c.Database.Type {
	case "mysql":
		if err := run("mariadb-install-db.exe", "--datadir="+dataDir(c), "--password="+super); err != nil {
			return err
		}
		return writeMyIni(c)
	case "pgsql":
		pw := filepath.Join(filepath.FromSlash(c.DBDir()), "initdb.pw")
		if err := os.WriteFile(pw, []byte(super), 0o600); err != nil {
			return err
		}
		defer os.Remove(pw)
		return run("initdb.exe", "-D", dataDir(c), "-U", "postgres", "-E", "UTF8", "--locale=C", "--auth=scram-sha-256", "--pwfile="+pw)
	}
	return fmt.Errorf("unsupported bundled type %q", c.Database.Type)
}

// superSQL runs one statement as the bundled server's superuser, connected to
// database dbName ("" for the server's maintenance database), and returns its
// unformatted output. Errors are also written to logf.
func superSQL(ctx context.Context, c config.Config, logf *os.File, dbName, sql string) (string, error) {
	super, err := readSecret(c)
	if err != nil {
		return "", err
	}
	port := strconv.Itoa(c.Database.Port)
	var cmd *exec.Cmd
	switch c.Database.Type {
	case "mysql":
		args := []string{"-h", "127.0.0.1", "-P", port, "-u", "root", "-N", "-B", "-e", sql}
		if dbName != "" {
			args = append(args, dbName)
		}
		cmd = exec.CommandContext(ctx, filepath.Join(binDir(c), "mariadb.exe"), args...)
		cmd.Env = append(os.Environ(), "MYSQL_PWD="+super)
	case "pgsql":
		if dbName == "" {
			dbName = "postgres"
		}
		cmd = exec.CommandContext(ctx, filepath.Join(binDir(c), "psql.exe"), "-h", "127.0.0.1", "-p", port, "-U", "postgres", "-d", dbName,
			"-v", "ON_ERROR_STOP=1", "-X", "-q", "-t", "-A", "-c", sql)
		cmd.Env = append(os.Environ(), "PGPASSWORD="+super)
	default:
		return "", fmt.Errorf("unsupported bundled type %q", c.Database.Type)
	}
	var stderr strings.Builder
	cmd.Stderr = &stderr
	cmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true}
	out, err := cmd.Output()
	if err != nil {
		msg := strings.TrimSpace(stderr.String())
		fmt.Fprintf(logf, "%s: %v: %s\n", filepath.Base(cmd.Path), err, msg)
		return "", fmt.Errorf("%s: %v: %s", filepath.Base(cmd.Path), err, msg)
	}
	return strings.TrimSpace(string(out)), nil
}

func sqlString(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }
func pgIdent(s string) string   { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }
func myIdent(s string) string   { return "`" + strings.ReplaceAll(s, "`", "``") + "`" }

// CreateAppUser makes sure the Nextcloud database and user exist on a running
// bundled server, with the password from ncwin.toml. Safe to repeat.
func CreateAppUser(ctx context.Context, c config.Config, logf *os.File) error {
	d := c.Database
	switch d.Type {
	case "mysql":
		user := sqlString(d.User) + "@'127.0.0.1'"
		_, err := superSQL(ctx, c, logf, "", "CREATE DATABASE IF NOT EXISTS "+myIdent(d.Name)+" CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;"+
			"CREATE USER IF NOT EXISTS "+user+" IDENTIFIED BY "+sqlString(d.Password)+";"+
			"ALTER USER "+user+" IDENTIFIED BY "+sqlString(d.Password)+";"+
			"GRANT ALL PRIVILEGES ON "+myIdent(d.Name)+".* TO "+user+"; FLUSH PRIVILEGES;")
		return err
	case "pgsql":
		// One statement per call: CREATE DATABASE refuses to run inside the
		// transaction psql wraps a multi-statement -c in.
		role, err := superSQL(ctx, c, logf, "", "SELECT 1 FROM pg_roles WHERE rolname = "+sqlString(d.User))
		if err != nil {
			return err
		}
		verb := "CREATE"
		if role == "1" {
			verb = "ALTER"
		}
		if _, err := superSQL(ctx, c, logf, "", verb+" USER "+pgIdent(d.User)+" WITH PASSWORD "+sqlString(d.Password)+" CREATEDB"); err != nil {
			return err
		}
		exists, err := superSQL(ctx, c, logf, "", "SELECT 1 FROM pg_database WHERE datname = "+sqlString(d.Name))
		if err != nil || exists == "1" {
			return err
		}
		_, err = superSQL(ctx, c, logf, "", createPGDatabase(d))
		return err
	}
	return fmt.Errorf("unsupported bundled type %q", d.Type)
}

func createPGDatabase(d config.Database) string {
	return "CREATE DATABASE " + pgIdent(d.Name) + " OWNER " + pgIdent(d.User) + " TEMPLATE template0 ENCODING 'UTF8'"
}

// ResetIncomplete empties the Nextcloud database when an earlier setup left
// tables behind without finishing the install, so maintenance:install can run
// again. It refuses (and changes nothing) if the database records a completed
// install: Nextcloud stores core/installedat only after its schema and apps
// are in place, so its presence means real data, whatever config.php says.
func ResetIncomplete(ctx context.Context, c config.Config, logf *os.File) error {
	d := c.Database
	schema := map[string]string{"mysql": sqlString(d.Name), "pgsql": "'public'"}[d.Type]
	tables, err := superSQL(ctx, c, logf, d.Name, "SELECT count(*) FROM information_schema.tables WHERE table_schema = "+schema)
	if err != nil || tables == "0" {
		return err
	}
	hasAppconfig, err := superSQL(ctx, c, logf, d.Name, "SELECT count(*) FROM information_schema.tables WHERE table_schema = "+schema+" AND table_name = 'oc_appconfig'")
	if err != nil {
		return err
	}
	if hasAppconfig != "0" {
		done, err := superSQL(ctx, c, logf, d.Name, "SELECT count(*) FROM oc_appconfig WHERE appid = 'core' AND configkey = 'installedat'")
		if err != nil {
			return err
		}
		if done != "0" {
			return fmt.Errorf("database %q holds a completed Nextcloud install, but config.php does not say installed; "+
				"restore config.php from a backup instead of running setup", d.Name)
		}
	}
	fmt.Fprintf(logf, "database %q has %s tables from an unfinished install; recreating it\n", d.Name, tables)
	switch d.Type {
	case "mysql":
		_, err = superSQL(ctx, c, logf, "", "DROP DATABASE "+myIdent(d.Name)+"; CREATE DATABASE "+myIdent(d.Name)+" CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci")
		return err
	case "pgsql":
		if _, err := superSQL(ctx, c, logf, "", "DROP DATABASE "+pgIdent(d.Name)+" WITH (FORCE)"); err != nil {
			return err
		}
		_, err = superSQL(ctx, c, logf, "", createPGDatabase(d))
		return err
	}
	return fmt.Errorf("unsupported bundled type %q", d.Type)
}

// DBStopTimeout is how long a bundled server gets to shut down cleanly before
// it is killed. Shutdown waits for any in-progress checkpoint, which on slow
// disks has been measured at ~5 minutes; killing mid-checkpoint is the worst
// outcome, so this is generous. The service's SCM wait hints cover it.
const DBStopTimeout = 15 * time.Minute

// Spec returns the supervised child for the bundled server.
func Spec(c config.Config) (proc.Spec, error) {
	logPath := filepath.Join(filepath.FromSlash(c.LogDir()), "db.log")
	// Both servers accept TCP before they accept sessions ("the database
	// system is starting up"), so readiness uses each server's own probe.
	port := strconv.Itoa(c.Database.Port)
	probe := map[string][]string{
		"mysql": {"mariadb-admin.exe", "--host=127.0.0.1", "--port=" + port, "--connect-timeout=5", "ping"},
		"pgsql": {"pg_isready.exe", "-h", "127.0.0.1", "-p", port, "-t", "5"},
	}[c.Database.Type]
	ready := func(ctx context.Context) error {
		cmd := exec.CommandContext(ctx, filepath.Join(binDir(c), probe[0]), probe[1:]...)
		cmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true}
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("%s: %v: %s", probe[0], err, strings.TrimSpace(string(out)))
		}
		return nil
	}
	switch c.Database.Type {
	case "mysql":
		if err := writeMyIni(c); err != nil {
			return proc.Spec{}, err
		}
		return proc.Spec{
			Name: "db", Path: filepath.Join(binDir(c), "mariadbd.exe"),
			Args: []string{"--defaults-file=" + myIni(c), "--console"},
			Log:  logPath, Ready: ready, PreStart: func() error { return proc.PortsFree(c.Database.Port) },
			Stop: func(ctx context.Context) error {
				super, err := readSecret(c)
				if err != nil {
					return err
				}
				cmd := exec.CommandContext(ctx, filepath.Join(binDir(c), "mariadb-admin.exe"), "-h", "127.0.0.1", "-P", strconv.Itoa(c.Database.Port), "-u", "root", "shutdown")
				cmd.Env = append(os.Environ(), "MYSQL_PWD="+super)
				cmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true}
				return cmd.Run()
			},
			StopTimeout: DBStopTimeout,
		}, nil
	case "pgsql":
		return proc.Spec{
			Name: "db", Path: filepath.Join(binDir(c), "postgres.exe"),
			// postgres.exe refuses to run with administrative rights; the
			// service account (NT SERVICE\ncwin) is unprivileged.
			Args:         []string{"-D", dataDir(c), "-p", strconv.Itoa(c.Database.Port), "-c", "listen_addresses=127.0.0.1"},
			Unprivileged: true,
			Log:          logPath, Ready: ready, PreStart: func() error { return proc.PortsFree(c.Database.Port) },
			Stop: func(ctx context.Context) error {
				cmd := exec.CommandContext(ctx, filepath.Join(binDir(c), "pg_ctl.exe"), "stop", "-D", dataDir(c), "-m", "fast", "-W")
				cmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true}
				return cmd.Run()
			},
			StopTimeout: DBStopTimeout,
		}, nil
	}
	return proc.Spec{}, fmt.Errorf("unsupported bundled type %q", c.Database.Type)
}
